package dev.brikk.ducklake.corpus

import dev.brikk.ducklake.slt.SltParser
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test

/** H02: independent wrong answers must fail through the real JDBC/driver path. */
internal class TestGoldenComparisonIntegrity {
    private fun result(types: String, sql: String, expected: String, options: String = ""): FileResult =
        ReplayDriver().replay(SltParser.parse("typed.test", "query $types $options\n$sql\n----\n$expected\n\n"))

    private fun fails(types: String, sql: String, expected: String, options: String = "") {
        val result = result(types, sql, expected, options)
        assertThat(result.failed).`as`("$sql vs $expected").hasSize(1)
        assertThat(result.skipped).isEmpty()
    }

    private fun passes(types: String, sql: String, expected: String, options: String = "") {
        val result = result(types, sql, expected, options)
        assertThat(result.failed).`as`("$sql vs $expected").isEmpty()
        assertThat(result.passed).isEqualTo(1)
    }

    @Test fun adjacentLargeIntegersNeverUseFloatingTolerance() {
        for (types in listOf("I", "R", "T")) {
            fails(types, "SELECT 10000000001::BIGINT", "10000000000")
            fails(types, "SELECT 9007199254740993::BIGINT", "9007199254740992")
            fails(types, "SELECT 170141183460469231731687303715884105727::HUGEINT", "170141183460469231731687303715884105726")
            passes(types, "SELECT 10000000001::BIGINT", "10000000001")
        }
        passes("I", "SELECT 1::BIGINT", "1.0")
    }

    @Test fun decimalDifferencesAreExactWhileRealResultsRetainTolerance() {
        fails("R", "SELECT 10000000000.000000001::DECIMAL(38,9)", "10000000000.000000000")
        passes("R", "SELECT 1.50::DECIMAL(10,2)", "1.5")
        passes("R", "SELECT 1.0000000001::DOUBLE", "1.0")
        fails("R", "SELECT 1.001::DOUBLE", "1.0")
    }

    @Test fun booleanCoercionRequiresAnActualSqlBoolean() {
        for (types in listOf("I", "R", "T")) {
            fails(types, "SELECT 'true'::VARCHAR", "1")
            fails(types, "SELECT 'false'::VARCHAR", "0")
            fails(types, "SELECT 'True'::VARCHAR", "true")
            fails(types, "SELECT '10000000001'::VARCHAR", "10000000000")
            passes(types, "SELECT true", "1")
            passes(types, "SELECT false", "FALSE")
            fails(types, "SELECT true", "0")
        }
    }

    @Test fun actualAndExpectedShapesMustMatchTheDeclarationBeforeSorting() {
        for (sort in listOf("nosort", "rowsort", "valuesort")) {
            fails("I", "SELECT 1,2", "1\t2", sort)
            fails("II", "SELECT 1", "1", sort)
            fails("I", "SELECT 1,2 WHERE false", "", sort)
            passes("II", "SELECT 1,2 WHERE false", "", sort)
            passes("II", "SELECT 1,2", "1\t2", sort)
            passes("II", "SELECT 1,2", "1\n2", sort)
        }
    }

    @Test fun labelsAndHashGoldensCannotBypassShapeChecks() {
        // Known MD5("1\n2\n"), not generated by the comparator under test.
        val hash = "2 values hashing to 6ddb4095eb719e2a9f0a3f95677d24e0"
        fails("I", "SELECT 1,2", hash)
        passes("II", "SELECT 1,2", hash)
    }

    @Test fun labelPlaceholderWidthIsNotAnAssertionButLaterActualShapeIs() {
        // Pinned upstream labelled all-types queries use I as a placeholder for wide results.
        passes("I", "SELECT 1,2", "ignored", "nosort label")
        passes("I", "SELECT 1,2 WHERE false", "ignored", "nosort label")
        val text = "query I nosort label\nSELECT 1,2\n----\n\n" +
            "query I nosort label\nSELECT * FROM (VALUES (1),(2)) t(x)\n----\n\n" +
            "query I nosort empty\nSELECT 1,2 WHERE false\n----\n\n" +
            "query I nosort empty\nSELECT 1 WHERE false\n----\n\n"
        val result = ReplayDriver().replay(SltParser.parse("label-shape.test", text))
        assertThat(result.passed).isEqualTo(2)
        assertThat(result.failed).hasSize(2).allSatisfy { assertThat(it.reason).contains("column count changed") }
    }

    @Test fun nonResultCommandsAreDistinctFromEmptyTypedSelects() {
        val text = "query I\nCREATE TABLE t(i INTEGER)\n----\n\n" +
            "query I\nALTER TABLE t ADD COLUMN j INTEGER\n----\n\n" +
            "query I\nCREATE VIEW v AS SELECT * FROM t\n----\n\n" +
            "query II\nDROP VIEW v\n----\n\n" + // wrong declaration must fail even without a result set
            "query I\nDROP TABLE t\n----\n\n"
        val result = ReplayDriver().replay(SltParser.parse("ddl-shape.test", text))
        assertThat(result.passed).isEqualTo(4)
        assertThat(result.failed).singleElement().extracting { it.reason }.asString().contains("column count")
        fails("I", "CREATE TABLE no_values(i INTEGER)", "1")
        passes("I", "CREATE TABLE no_values(i INTEGER)", "0 values hashing to d41d8cd98f00b204e9800998ecf8427e")
    }

    @Test fun retainingMetadataMustNotRebindSideEffectingTableFunctions() {
        val text = "statement ok\nLOAD ducklake\n\nstatement ok\n" +
            "ATTACH 'ducklake:{TEST_DIR}/meta.db' AS lake (DATA_PATH '{TEST_DIR}/data', " +
            "DUCKLAKE_VERSION '1.0', AUTOMATIC_MIGRATION FALSE, DATA_INLINING_ROW_LIMIT 10)\n\n" +
            "statement ok\nCREATE TABLE lake.t(i INTEGER); INSERT INTO lake.t VALUES(1)\n\n" +
            "query II\nSELECT count(*),max(snapshot_id) FROM lake.snapshots()\n----\n3\t2\n\n" +
            "query II\nSELECT count(*),sum(rows_flushed) FROM ducklake_flush_inlined_data('lake')\n----\n1\t1\n\n" +
            "query II\nSELECT count(*),max(snapshot_id) FROM lake.snapshots()\n----\n4\t3\n\n"
        val result = ReplayDriver().replay(SltParser.parse("single-bind.test", text))
        assertThat(result.failed).isEmpty()
        assertThat(result.passed).isEqualTo(6)
    }
}
